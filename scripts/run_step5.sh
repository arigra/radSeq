#!/usr/bin/env bash
# Step 5 (docs/notes/2026-10-22-step5-source-only-and-headroom.md):
#  A  source-only detectors: simulator data alone vs DiT data alone, tested on
#     real -- did fine-tuning teach the generator real vehicles?
#  B1 real-only learning curve on nested subsets of 25/50/100/200 sequences
#  B2 at the largest size with headroom (step5_choose_n.py): fine-tune both
#     DiTs on that subset only, render, score the three step 4 arms, and run
#     the memorisation check
#
# Every stage is resumable: finished ones are skipped (a detector report is
# finished only once it says "complete"), trainings continue from last.pt,
# renderings redo only their unfinished part, detector arms keep scored seeds.
set -euo pipefail
cd "$(dirname "$0")/.."
PY="${PY:-$(command -v python3)}"
LOG=logs/step5.log
export PYTHONPATH=.
say() { echo "$(date '+%F %T') | $*" >> "$LOG"; }

if pgrep -f "^bash scripts/run_step5.sh" | grep -vx "$$" >/dev/null; then
  say "REFUSED: another run_step5.sh is already running"; exit 1
fi

arms() {  # arms <out.json> <radial_detector_arms.py args...>
  local out=$1; shift
  if ! grep -q '"complete": true' "$out" 2>/dev/null; then
    say "detector arms -> $out"
    "$PY" scripts/radial_detector_arms.py --out "$out" "$@" >> "$LOG" 2>&1
  fi
}

say "start"
for variant in engineer fitted; do
  arms "samples/step5_source_only_${variant}.json" --variant "$variant" \
      --synthetic "data/radial_synth_${variant}" --arms sim,dit
done

for n in 25 50 100 200; do
  "$PY" scripts/make_radial_subset.py --n "$n" >> "$LOG" 2>&1
  arms "samples/step5_curve_n${n}.json" --variant engineer \
      --real "data/radial_seq_n${n}" --arms real
done

nstar=$("$PY" scripts/step5_choose_n.py)
say "headroom rule chose N=${nstar} (samples/step5_headroom.json)"
if [ "$nstar" = "none" ]; then say "no size has headroom; B2 skipped"; say "DONE"; exit 0; fi

cache="data/radial_seq_n${nstar}"
for variant in engineer fitted; do
  tag="${variant}_n${nstar}"
  cfg="configs/finetune_${tag}.yaml"
  ckpt="checkpoints/finetune_${tag}"
  # Same recipe and the same 9,600 optimizer steps as the 387-sequence fine-tune;
  # the subset is repeated so an epoch stays ~50 steps long.
  "$PY" - "$variant" "$nstar" "$cfg" <<'EOF'
import math, sys, yaml
variant, n, out = sys.argv[1], int(sys.argv[2]), sys.argv[3]
cfg = yaml.safe_load(open(f"configs/finetune_{variant}.yaml"))
rep = math.ceil(400 / n)
per_epoch = n * rep // cfg["train"]["batch_size"]
cfg["data"].update(cache_dir=f"data/radial_seq_n{n}", train_repeat=rep)
cfg["train"].update(epochs=math.ceil(9600 / per_epoch), snapshot_every_epochs=0,
                    ckpt_dir=f"checkpoints/finetune_{variant}_n{n}",
                    log_file=f"logs/finetune_{variant}_n{n}.log")
open(out, "w").write(f"# Step 5 B2: fine-tune on the {n}-sequence real subset only "
                     f"(generated by run_step5.sh from finetune_{variant}.yaml)\n"
                     + yaml.safe_dump(cfg, sort_keys=False))
EOF
  if [ ! -f "$ckpt/STAGE_DONE" ]; then
    args=(--config "$cfg")
    [ -f "$ckpt/last.pt" ] && args+=(--resume "$ckpt/last.pt")
    say "$tag: fine-tuning"
    PYTORCH_CUDA_ALLOC_CONF=expandable_segments:True "$PY" -m src.train "${args[@]}" >> "$LOG" 2>&1
    touch "$ckpt/STAGE_DONE"
  fi
  say "$tag: rendering generated sequences"
  "$PY" scripts/gen_scene_synthetic.py --ckpt "$ckpt/last.pt" --cache "$cache" \
      --out "data/radial_synth_${tag}" --repeats 4 --guidance 1 >> "$LOG" 2>&1
  arms "samples/step5_arms_${tag}.json" --variant "$variant" --real "$cache" \
      --synthetic "data/radial_synth_${tag}"
  mem="samples/step5_memorization_${tag}.json"
  if [ ! -f "$mem" ]; then
    say "$tag: memorisation check"
    "$PY" scripts/memorization_check_scene.py --ckpt "$ckpt/last.pt" --cache "$cache" \
        --n $(( nstar < 32 ? nstar : 32 )) --out "$mem" >> "$LOG" 2>&1
  fi
  say "$tag: done"
done
say "DONE"
